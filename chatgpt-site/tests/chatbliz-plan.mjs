import assert from 'node:assert/strict';
import {chatblizPlan} from '../worker/chatbliz-plan.mjs';
const origin='https://chatbliz.example';
const make=(message,options={})=>new Request(origin+'/api/chatbliz/plan',{method:'POST',headers:{origin, 'content-type':'application/json',...(options.auth?{'oai-authenticated-user-id':'test-user'}:{}),...(options.headers||{})},body:JSON.stringify({message})});
const guest=await chatblizPlan(make('Build a website'));
assert.equal(guest.status,401);
const crossOrigin=await chatblizPlan(make('Build a website',{auth:true,headers:{origin:'https://other.example'}}));
assert.equal(crossOrigin.status,403);
const result=await chatblizPlan(make('Build a website',{auth:true}));
assert.equal(result.status,200);
const data=await result.json();
assert.equal(data.status,'planned');
assert.equal(data.executed,false);
assert.equal(data.requiresApproval,true);
assert.equal(data.service.id,'my-website');
assert.equal(data.nextAction.url,'/website-editor.html');
const empty=await chatblizPlan(make('',{auth:true}));
assert.equal(empty.status,400);
console.log('Chatbliz plan API contract tests passed');
